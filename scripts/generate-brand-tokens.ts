import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import {
  brandColors,
  brandHex,
  brandPastels,
  dashboardAccessThemeKeys,
  dashboardTheme,
  horizonteRoot,
  neutralColors,
  siteTheme,
} from "@aohys/core/brand-tokens";

// Generates the site and dashboard theme variables and the Horizonte `:root`
// from packages/core/src/brand-tokens.ts. `--check` fails when a generated
// artifact drifts or a brand color literal appears elsewhere in apps/*/src.

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = "packages/core/src/brand-tokens.ts";
const DASHBOARD_THEME = path.join(
  root,
  "apps/dashboard/src/lib/brand-theme.generated.ts",
);
const SITE_THEME = path.join(
  root,
  "apps/site/src/styles/brand-theme.generated.ts",
);
const HORIZONTE_CSS = path.join(root, "apps/site/src/styles/horizonte.css");
const CSS_BEGIN = "/* BEGIN brand-tokens (generated by pnpm brand:generate) */";
const CSS_END = "/* END brand-tokens */";
const SCANNED_ROOTS = ["apps/site/src", "apps/dashboard/src"];
const SCANNED_EXTENSIONS = new Set([
  ".ts",
  ".tsx",
  ".astro",
  ".css",
  ".js",
  ".jsx",
  ".mjs",
  ".json",
]);

const HEADER = `// Generated by pnpm brand:generate from ${SOURCE}. Do not edit.\n`;

function tailwindVars(vars: Record<string, string>): string[] {
  return Object.entries(vars).map(
    ([name, value]) => `[${name}:${value.replaceAll(" ", "_")}]`,
  );
}

function stringArray(name: string, classes: string[]): string {
  return `export const ${name} = [\n${classes
    .map((value) => `  ${JSON.stringify(value)},`)
    .join("\n")}\n].join(" ");\n`;
}

function renderDashboardTheme(): string {
  return `${HEADER}\n${stringArray("dashboardColorVars", tailwindVars(dashboardTheme))}`;
}

function renderSiteTheme(): string {
  const access = Object.fromEntries(
    dashboardAccessThemeKeys.map((key) => [key, dashboardTheme[key]]),
  );
  return `${HEADER}\n${stringArray("siteColorVars", tailwindVars(siteTheme))}\n${stringArray(
    "dashboardAccessColorVars",
    tailwindVars(access),
  )}`;
}

function renderHorizonteCss(current: string): string {
  const start = current.indexOf(CSS_BEGIN);
  const end = current.indexOf(CSS_END);
  if (start === -1 || end === -1 || end < start) {
    throw new Error(
      `${path.relative(root, HORIZONTE_CSS)} is missing the brand-tokens markers.`,
    );
  }
  const block = [
    CSS_BEGIN,
    "@property --wash {",
    '  syntax: "<color>";',
    "  inherits: true;",
    `  initial-value: ${horizonteRoot["--wash"]};`,
    "}",
    "",
    ":root {",
    ...Object.entries(horizonteRoot).map(
      ([name, value]) => `  ${name}: ${value};`,
    ),
    "}",
    CSS_END,
  ].join("\n");
  return `${current.slice(0, start)}${block}${current.slice(end + CSS_END.length)}`;
}

// Canonical OKLCH components, so `0.50`, `0.5` and `50%` compare equal.
const normalizeOklch = (body: string) =>
  body
    .replaceAll("_", " ")
    .trim()
    .split(/[\s/]+/)
    .map((part, index) => {
      const percent = part.endsWith("%");
      const value = Number(part.replace(/%$|deg$/i, ""));
      if (Number.isNaN(value)) return part.toLowerCase();
      return String(percent && index === 0 ? value / 100 : value);
    })
    .join(" ");

const neutral = new Set(neutralColors.map((value) => value.toLowerCase()));
const brandHexLiterals = new Set(
  [
    ...Object.values(brandPastels),
    ...Object.values(brandHex),
    ...Object.values(horizonteRoot),
  ]
    .map((value) => value.toLowerCase())
    .filter((value) => !neutral.has(value)),
);
const brandOklchLiterals = new Set(
  [
    ...Object.values(brandColors),
    ...Object.values(siteTheme),
    ...Object.values(dashboardTheme),
  ]
    .filter((value) => !neutral.has(value))
    .map((value) => normalizeOklch(value.slice("oklch(".length, -1))),
);

function* sourceFiles(dir: string): Generator<string> {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const file = path.join(dir, entry.name);
    if (entry.isDirectory()) yield* sourceFiles(file);
    else if (
      SCANNED_EXTENSIONS.has(path.extname(entry.name)) &&
      file !== DASHBOARD_THEME &&
      file !== SITE_THEME
    ) {
      yield file;
    }
  }
}

// Only horizonte.css carries a generated region; markers elsewhere are scanned.
function withoutGeneratedRegion(file: string, text: string): string {
  if (file !== HORIZONTE_CSS) return text;
  const start = text.indexOf(CSS_BEGIN);
  const end = text.indexOf(CSS_END);
  return start === -1 || end === -1
    ? text
    : text.slice(0, start) + text.slice(end + CSS_END.length);
}

function brandLiterals(): string[] {
  const findings: string[] = [];
  for (const scanned of SCANNED_ROOTS) {
    for (const file of sourceFiles(path.join(root, scanned))) {
      const lines = withoutGeneratedRegion(
        file,
        readFileSync(file, "utf8"),
      ).split("\n");
      lines.forEach((line, index) => {
        const hexes = [...line.matchAll(/#[0-9a-fA-F]{6}\b/g)].map(
          ([hex]) => hex,
        );
        const oklchs = [...line.matchAll(/oklch\(([^)]*)\)/gi)].map(
          ([literal, body]) => ({
            literal,
            body: normalizeOklch(body ?? ""),
          }),
        );
        for (const hex of hexes) {
          if (brandHexLiterals.has(hex.toLowerCase())) {
            findings.push(`${path.relative(root, file)}:${index + 1} ${hex}`);
          }
        }
        for (const { literal, body } of oklchs) {
          if (brandOklchLiterals.has(body)) {
            findings.push(
              `${path.relative(root, file)}:${index + 1} ${literal}`,
            );
          }
        }
      });
    }
  }
  return findings;
}

function main(): void {
  const check = process.argv.includes("--check");
  const artifacts = [
    { file: DASHBOARD_THEME, expected: renderDashboardTheme() },
    { file: SITE_THEME, expected: renderSiteTheme() },
    {
      file: HORIZONTE_CSS,
      expected: renderHorizonteCss(readFileSync(HORIZONTE_CSS, "utf8")),
    },
  ];
  const read = (file: string) => {
    try {
      return readFileSync(file, "utf8");
    } catch {
      return undefined;
    }
  };
  const drifted = artifacts.filter(
    ({ file, expected }) => read(file) !== expected,
  );

  if (check) {
    const literals = brandLiterals();
    const problems = [
      ...(drifted.length > 0
        ? [
            `Brand artifacts drifted from ${SOURCE}: ${drifted
              .map(({ file }) => path.relative(root, file))
              .join(", ")}. Run pnpm brand:generate.`,
          ]
        : []),
      ...(literals.length > 0
        ? [
            `Brand color literals outside ${SOURCE}; use the generated variables or import the token:\n  ${literals.join("\n  ")}`,
          ]
        : []),
    ];
    if (problems.length > 0) throw new Error(problems.join("\n"));
    console.log(
      "Brand artifacts match the tokens and no brand literal escapes them.",
    );
    return;
  }

  for (const { file, expected } of drifted) writeFileSync(file, expected);
  console.log(
    drifted.length > 0
      ? `Regenerated ${drifted.map(({ file }) => path.relative(root, file)).join(", ")}.`
      : "Brand artifacts already match the tokens.",
  );
}

main();
