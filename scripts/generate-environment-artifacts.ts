import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import {
  RELEASE_ENVIRONMENTS,
  type ReleaseEnvironment,
} from "@aohys/core/domain";
import {
  getEnvironmentVariableDefinitions,
  type EnvironmentVariableDefinition,
  type ProviderName,
} from "@aohys/environment";

// Generates the release workflow env blocks and .env.example from the
// Environment Contract. `--check` fails when a committed artifact drifts.

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const WORKFLOW = path.join(root, ".github/workflows/release-train.yml");
const ENV_EXAMPLE = path.join(root, ".env.example");
const BEGIN = "# BEGIN environment-contract (generated by pnpm env:generate)";
const END = "# END environment-contract";

const EXAMPLE_SECTIONS: Record<ProviderName, string> = {
  core: "Core site and public contact configuration.",
  convex: "Convex provider outputs.",
  posthog:
    "Production-only PostHog public key. Leave empty locally and in preview.\n# Browser and server events use the first-party /ingest proxy.",
  resend: "Resend server-side notification configuration.",
  "better-auth": "Better Auth server-side configuration.",
  cloudflare: "Cloudflare release/media configuration.",
  github: "GitHub release and publication configuration.",
};

function githubValue(
  definition: EnvironmentVariableDefinition,
  environment: ReleaseEnvironment,
): string | undefined {
  const github = definition.github;
  if (!github || !definition.destinations.includes("release-job")) return;
  if (!(github.environments ?? RELEASE_ENVIRONMENTS).includes(environment)) {
    return;
  }
  switch (github.source) {
    case "environment-name":
      return environment;
    case "release-sha":
      return "${{ github.sha }}";
    case "variable":
      return `\${{ vars.${definition.name} }}`;
    case "secret":
      return `\${{ secrets.${definition.name} }}`;
  }
}

function workflowEnvBlock(
  definitions: readonly EnvironmentVariableDefinition[],
  environment: ReleaseEnvironment,
  indent: string,
): string {
  const lines = definitions.flatMap((definition) => {
    const value = githubValue(definition, environment);
    return value === undefined ? [] : [`${indent}${definition.name}: ${value}`];
  });
  return [`${indent}${BEGIN}`, ...lines, `${indent}${END}`].join("\n");
}

// Replaces the generated block inside the `env:` of the job that deploys to
// `environment`, identified by its `environment: <name>` key.
function renderWorkflow(
  source: string,
  definitions: readonly EnvironmentVariableDefinition[],
): string {
  let rendered = source;
  for (const environment of RELEASE_ENVIRONMENTS) {
    const pattern = new RegExp(
      `(\\n    environment: ${environment}\\n    env:\\n)( +)${escape(BEGIN)}\\n(?:\\2[A-Z_0-9]+: [^\\n]*\\n)*\\2${escape(END)}`,
    );
    const match = rendered.match(pattern);
    if (!match) {
      throw new Error(
        `release-train.yml has no generated env block for ${environment}; add the ${BEGIN} / ${END} markers under its env:.`,
      );
    }
    rendered = rendered.replace(
      pattern,
      `$1${workflowEnvBlock(definitions, environment, match[2] ?? "      ")}`,
    );
  }
  return rendered;
}

function escape(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function renderEnvExample(
  definitions: readonly EnvironmentVariableDefinition[],
): string {
  const sections: string[] = [
    "# AOHYS Environment Contract example values (generated by pnpm env:generate).\n# Copy to .env.local for local development. Do not commit real secrets.",
  ];
  const providers = [
    ...new Set(definitions.map((definition) => definition.provider)),
  ];
  for (const provider of providers) {
    const lines = definitions
      .filter(
        (definition) =>
          definition.provider === provider &&
          definition.localExample !== undefined,
      )
      .map(
        (definition) =>
          `${definition.name}=${formatExampleValue(definition.localExample ?? "")}`,
      );
    if (lines.length > 0) {
      sections.push(`# ${EXAMPLE_SECTIONS[provider]}\n${lines.join("\n")}`);
    }
  }
  return `${sections.join("\n\n")}\n`;
}

function formatExampleValue(value: string): string {
  return /[\s"#]/.test(value) ? JSON.stringify(value) : value;
}

function main(): void {
  const check = process.argv.includes("--check");
  const definitions = getEnvironmentVariableDefinitions();
  const artifacts = [
    {
      file: WORKFLOW,
      expected: renderWorkflow(readFileSync(WORKFLOW, "utf8"), definitions),
    },
    { file: ENV_EXAMPLE, expected: renderEnvExample(definitions) },
  ];
  const drifted = artifacts.filter(
    ({ file, expected }) => readFileSync(file, "utf8") !== expected,
  );

  if (check) {
    if (drifted.length > 0) {
      throw new Error(
        `Environment artifacts drifted from the contract: ${drifted
          .map(({ file }) => path.relative(root, file))
          .join(", ")}. Run pnpm env:generate.`,
      );
    }
    console.log("Environment artifacts match the contract.");
    return;
  }

  for (const { file, expected } of drifted) writeFileSync(file, expected);
  console.log(
    drifted.length > 0
      ? `Regenerated ${drifted.map(({ file }) => path.relative(root, file)).join(", ")}.`
      : "Environment artifacts already match the contract.",
  );
}

main();
